(r/'native/BodyOptions.h').write_text('// Generated by tools/build_body_data.py\n#pragma once\nstruct BodyOption { unsigned char race,sex,kind,a,b; };\nstatic const BodyOption bodyOptions[] = {\n'+''.join('{'+','.join(map(str,v))+'},\n' for v in valid)+'};\n')
(r/'research/body-options.json').write_text(json.dumps(data,indent=2))
