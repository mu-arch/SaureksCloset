"""Freeze build-5875 mount spell mappings and focused sound regression fixtures.

Usage: python3 tools/build_mount_sounds.py Spell.dbc SpellVisual.dbc SpellVisualKit.dbc
Only numeric mount metadata is emitted; no audio or complete DBC is distributed.
"""
import hashlib
import json
from pathlib import Path
import struct
import sys

root = Path(__file__).resolve().parents[1]
metadata = json.loads((root/'addon/SaureksCloset/MOUNTS-SOURCE.json').read_text())
def dbc(path, fields):
    data = Path(path).read_bytes()
    magic, count, actual, size, strings = struct.unpack_from('<4s4I', data)
    assert magic == b'WDBC' and actual == fields and size == fields*4
    assert len(data) == 20+count*size+strings
    rows = {r[0]: r for r in struct.iter_unpack('<%dI' % fields, data[20:20+count*size])}
    return rows, hashlib.sha256(data).hexdigest()

spells, sh = dbc(sys.argv[1], 173)
visuals, vh = dbc(sys.argv[2], 16)
kits, kh = dbc(sys.argv[3], 35)
assert sh == metadata['dbc']['Spell.dbc']
entries = sorted(metadata['entries'], key=lambda e:e['id'])
# Later spell rows supply the current mount variant (e.g. corrected Kodo sound).
header = '// Generated by tools/build_mount_sounds.py; build 5875.\n#pragma once\n'
header += 'struct MountSoundEntry {unsigned display,spell;};\nstatic constexpr MountSoundEntry mountSoundEntries[]={\n'
header += ''.join('{%d,%d},\n' % (e['id'], e['spells'][-1]) for e in entries)
header += '''};
inline unsigned mountSoundSpell(unsigned display){
    unsigned lo=0,hi=sizeof(mountSoundEntries)/sizeof(mountSoundEntries[0]);
    while(lo<hi){const unsigned mid=lo+(hi-lo)/2;if(mountSoundEntries[mid].display<display)lo=mid+1;else hi=mid;}
    return lo<sizeof(mountSoundEntries)/sizeof(mountSoundEntries[0])&&mountSoundEntries[lo].display==display?mountSoundEntries[lo].spell:0;
}
'''
(root/'native/MountSoundCatalog.h').write_text(header)
ids = sorted({i for e in entries for i in e['spells']})
used_visuals = {spells[i][115] for i in ids if spells[i][115] in visuals}
used_kits = sorted({k for v in used_visuals for k in visuals[v][1:6] if k in kits})
values = lambda row: ','.join('~0u' if n == 0xffffffff else str(n)+'u' for n in row)
fixture = '// Generated by tools/build_mount_sounds.py; build 5875.\n'
fixture += f'// Spell SHA256: {sh}\n// SpellVisual SHA256: {vh}\n// SpellVisualKit SHA256: {kh}\n#pragma once\n'
fixture += 'struct MountSpellFixture {unsigned id;std::array<unsigned,3> effects,auras;std::array<unsigned,16> visual;};\nstatic const MountSpellFixture mountSpellFixtures[]={\n'
for i in ids:
    s = spells[i]
    assert any(s[61+j] == 6 and s[91+j] == 78 for j in range(3))
    fixture += '{%du,{{%s}},{{%s}},{{%s}}},\n' % (i,values(s[61:64]),values(s[91:94]),values(visuals.get(s[115], [0]*16)))
fixture += '};\nstatic const std::array<unsigned,35> mountKitFixtures[]={\n'
fixture += ''.join('{{%s}},\n' % values(kits[k]) for k in used_kits)
fixture += '};\n'
(root/'tests/mount_sound_fixtures.h').write_text(fixture)
print('Generated',len(entries),'mount sound selections;',len(ids),'actual mounted spells and',len(used_kits),'visual kits for regression tests')
