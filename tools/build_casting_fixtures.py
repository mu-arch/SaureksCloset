"""Freeze caster-role coverage from extracted build-5875 client DBCs.

Usage: python tools/build_casting_fixtures.py Spell.dbc SpellVisual.dbc SpellVisualKit.dbc
No client archives or complete DBCs are distributed with these test cases.
"""
from pathlib import Path
import hashlib
import struct
import sys

def rows(path):
    raw = Path(path).read_bytes()
    assert raw[:4] == b'WDBC'
    count, fields, size, _ = struct.unpack_from('<4I', raw, 4)
    assert size == fields * 4
    return {r[0]: r for r in (struct.unpack_from('<'+'I'*fields, raw, 20+i*size)
                              for i in range(count))}, hashlib.sha256(raw).hexdigest()

spells, spell_hash = rows(sys.argv[1])
visuals, visual_hash = rows(sys.argv[2])
kits, kit_hash = rows(sys.argv[3])
assert len(next(iter(spells.values()))) == 173
assert len(next(iter(visuals.values()))) == 16
assert len(next(iter(kits.values()))) == 35
examples = {10, 6141, 8427, 10185, 10186, 10187, 116, 133, 1459, 5143, 15407, 740, 5740, 16914, 12051}
seen, cases, references = set(), [], 0
eligible = 0
for spell in spells.values():
    if spell[6] & (2 | 64) or 78 in spell[91:94]:
        continue
    eligible += 1
    visual = visuals.get(spell[115])
    if not visual:
        continue
    for phase, field in [(4, 1), (0, 2), (2, 5)]:
        kit = kits.get(visual[field])
        if not kit:
            continue
        references += 1
        key = phase, kit[1], kit[2], bool(visual[5])
        if key not in seen or spell[0] in examples:
            cases.append((spell[0], phase, kit, visual))
        seen.add(key)

def values(row):
    return ','.join('~0u' if v == 0xffffffff else str(v)+'u' for v in row)

text = ('// Generated by tools/build_casting_fixtures.py from Windows 1.12.1 build 5875.\n'
        f'// Spell SHA256: {spell_hash}\n// SpellVisual SHA256: {visual_hash}\n'
        f'// SpellVisualKit SHA256: {kit_hash}\n'
        f'// {eligible} eligible spells, {references} caster references, {len(seen)} distinct role/type/animation/channel combinations.\n'
        '#pragma once\nstruct CastingCase {unsigned spell,phase;weaponCasting::Kit kit;weaponCasting::Visual visual;};\n'
        'static const CastingCase castingCases[]={\n')
text += ''.join('{%du,%du,{{%s}},{{%s}}},\n' % (s, p, values(k), values(v)) for s, p, k, v in cases)
text += '};\n'
path = Path(__file__).resolve().parents[1]/'tests/casting_catalog_fixtures.h'
path.write_text(text)
print(f'Wrote {len(cases)} representative and named-spell fixtures covering {references} caster references.')
